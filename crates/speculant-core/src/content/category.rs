use serde::Deserialize;

/// Категория товаров (§5.2) из `data/categories/<категория>.toml`: по ней город задаёт множитель
/// цены, экран поездки называет, что в городе дешевле и что дороже, а сезон двигает цену по году.
#[derive(Clone, Debug, PartialEq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Category {
    /// Название строчными, как оно стоит в перечне: «видео и музыка».
    pub title: String,
    /// Сезон: двенадцать множителей цены, январь — декабрь. В середине месяца цена ровно такая,
    /// между серединами соседних месяцев идёт по прямой; без сезона цена круглый год одна.
    pub season: Option<[f64; 12]>,
}
